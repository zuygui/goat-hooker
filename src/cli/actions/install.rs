use colored::Colorize;

use goat_hooker::{errors::GoatHookerError, git, install};

pub fn install_hooks(force: bool) -> Result<(), GoatHookerError> {
    let cwd = std::env::current_dir()?;
    let root = git::repo_root(&cwd)?;

    let skipped = install::install_hooks(&root, force)?;
    for hook_path in &skipped {
        let shown = hook_path.strip_prefix(&root).unwrap_or(hook_path).display();
        match owner(hook_path) {
            Some(tool) => eprintln!(
                "{} kept {shown} {}",
                "!".yellow().bold(),
                format!(
                    "(installed by {tool}: `hooker install --force` lets Goat Hooker run your {tool} config as it is)"
                )
                .dimmed()
            ),
            None => eprintln!(
                "{} kept {shown} {}",
                "!".yellow().bold(),
                "(not installed by goat-hooker, use --force to replace it)".dimmed()
            ),
        }
    }

    let hooks_dir = git::hooks_dir(&root)?;
    let hooks_dir = hooks_dir.strip_prefix(&root).unwrap_or(&hooks_dir);
    println!(
        "{} Git hooks installed in {}",
        "✔".green(),
        hooks_dir.display()
    );
    Ok(())
}

/// The hooks manager that installed a Git hook
fn owner(hook: &std::path::Path) -> Option<&'static str> {
    let content = std::fs::read_to_string(hook).ok()?;
    [
        ("lefthook", "lefthook"),
        // "File generated by pre-commit: https://pre-commit.com"
        ("pre-commit.com", "pre-commit"),
        ("husky", "husky"),
    ]
    .into_iter()
    .find(|(marker, _)| content.contains(marker))
    .map(|(_, tool)| tool)
}
